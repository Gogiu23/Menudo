import type { Lang } from "../i18n";

/* Idioma del editor libre: el mismo que el editor principal (menudo:lang). Los textos están escritos en italiano en el código
   y este diccionario da su versión en español; si falta una entrada se ve el italiano. «ctx» separa palabras iguales con otro sentido. */
export const LANG_KEY = "menudo:lang";

export function loadLang(): Lang {
  try {
    const l = localStorage.getItem(LANG_KEY);
    if (l === "it" || l === "es") return l;
  } catch {}
  return navigator.language.startsWith("es") ? "es" : "it";
}

